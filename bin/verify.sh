#!/bin/sh
# verify.sh — the gate. Run this; it is the whole contract.
#
# Four things must hold. Any one failing exits non-zero.
#
#   1. the corpus passes the census      (positive control)
#   2. EVERY probe fails FOR ITS DECLARED REASON  (negative control -- a passing
#                                         probe means the alarm is broken, and a
#                                         probe that fails for some other reason
#                                         is a defense that has been removed
#                                         while the gate reports it active)
#   3. STATE.md regenerates identically  (no hand-typed numbers can survive)
#   4. no stray .lean outside lean/ and probes/
#   5. the per-file table cannot silently shorten (negative control, no toolchain)
#   6. a probe cannot be swapped for one that fails differently (negative control
#                                         for check 2 -- planted, not assumed)
#
# (5) exists because (3) is weaker than it reads. Check 3 asserts regeneration is
# DETERMINISTIC, not that it is COMPLETE. A table built by a regex that could not
# spell `Artin_Schreier2.lean` regenerated byte-identically every time and was
# wrong every time. Determinism is not correctness.
#
# (2) is the one that matters. A checker that has only ever been run on files
# that pass has no evidence behind it. Three separate holes in this project's
# checker were found by planting something false and watching it not ring:
#   * a `sorry` in a def that no theorem depended on
#   * an axiom outside the denylist
#   * declarations the extractor never matched, so were never probed at all
#
# (3) is what makes a wrong count unrepresentable rather than merely discouraged.

set -u
export PATH="/root/.elan/bin:$PATH"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT" || exit 2
fail=0
command -v lean >/dev/null 2>&1 || { echo "FAIL: no lean on PATH"; exit 2; }

echo "== 1. corpus census (positive control) =="
if ( cd lean && sh ../bin/check.sh ); then
    echo "   PASS"
else
    echo "   FAIL: corpus did not pass its own census"; fail=1
fi

echo
echo "== 2. negative controls (every probe MUST fail, FOR ITS DECLARED REASON) =="
# This check used to be named "every probe MUST be rejected" and assert only
# "every file in probes/ exits non-zero". Those are not the same claim, and the
# gap let a probe be swapped for one that fails differently -- silently removing
# a defense while this gate reported it active. bin/probes.sh checks the declared
# failure signature; the exit code is kept as a necessary condition, not as the
# assertion. Human lines go to stderr, table rows to stdout.
sh bin/probes.sh probes >/dev/null || fail=1

echo
echo "== 3. STATE.md is generated, not typed =="
tmp=$(mktemp)
sh bin/report.sh > "$tmp" 2>/dev/null
# the timestamp and wall-clock legitimately differ run to run; everything else
# must be byte-identical. strip only those two lines from both sides.
strip() { grep -v '^Generated: ' "$1" | grep -v '^| Census wall clock'; }
if [ ! -f STATE.md ]; then
    echo "   FAIL: STATE.md missing. run: sh bin/report.sh > STATE.md"; fail=1
elif strip "$tmp" > /tmp/.a && strip STATE.md > /tmp/.b && diff -u /tmp/.b /tmp/.a >/dev/null; then
    echo "   PASS: committed STATE.md matches a fresh generation"
else
    echo "   FAIL: STATE.md differs from a fresh generation --"
    echo "         either the corpus changed or someone edited it by hand."
    strip "$tmp" > /tmp/.a; strip STATE.md > /tmp/.b
    diff -u /tmp/.b /tmp/.a | head -40 | sed 's/^/         /'
    fail=1
fi
rm -f "$tmp" /tmp/.a /tmp/.b

echo
echo "== 4. no stray .lean outside lean/ and probes/ =="
stray=$(find . -name '*.lean' -not -path './lean/*' -not -path './probes/*' -not -path './.git/*')
if [ -z "$stray" ]; then echo "   PASS"; else echo "$stray" | sed 's/^/   FAIL: stray /'; fail=1; fi

echo
echo "== 5. the per-file table cannot silently shorten (negative control) =="
# Written by someone who did not write report.sh or perfile.sh. A probe written
# by the author tests what the author imagined, which is how the fifth regex
# survived: it was run on things that pass.
#
# Needs no toolchain. It exercises bin/perfile.sh -- the real code path report.sh
# uses, not a copy -- against filenames the deleted regex could not spell, and
# then against a census that is missing a record, to prove the alarm rings.
#
# Coverage of check.sh's REAL record format is not duplicated here: if that
# format drifts, perfile.sh aborts, report.sh exits non-zero, and check 3 above
# fails. A second gate on it would catch nothing this one does not.
d=$(mktemp -d)
: > "$d/Artin_Schreier2.lean"      # underscore AND digit -- the deleted regex spelled neither
: > "$d/Zero2.lean"                # digit only
: > "$d/Vieta.lean"                # the shape that used to pass, kept as the contrast
cat > "$d/census.txt" <<'CENSUS_FIXTURE'
PERFILE|Artin_Schreier2.lean|34|34
PERFILE|Zero2.lean|5|5
PERFILE|Vieta.lean|4|4
CENSUS_FIXTURE

rows=$(sh bin/perfile.sh "$d" "$d/census.txt"); prc=$?
nrows=$(printf '%s\n' "$rows" | grep -c '^|')
if [ "$prc" -ne 0 ]; then
    echo "   FAIL: perfile.sh errored on a complete census (exit $prc)"; fail=1
elif [ "$nrows" -ne 3 ]; then
    echo "   FAIL: 3 files, $nrows rows -- a row vanished, which is the bug this replaces"; fail=1
elif ! printf '%s\n' "$rows" | grep -q 'Artin_Schreier2\.lean' \
   || ! printf '%s\n' "$rows" | grep -q 'Zero2\.lean'; then
    echo "   FAIL: a file the old regex could not spell is still missing from the table"; fail=1
else
    echo "   PASS: underscore and digit filenames survive into the table (3 of 3)"
fi

# The other half, and the half that actually matters: prove the ABORT fires.
# A builder that never refuses is a builder that omits.
grep -v 'Zero2' "$d/census.txt" > "$d/census_short.txt"
if sh bin/perfile.sh "$d" "$d/census_short.txt" >/dev/null 2>&1; then
    echo "   FAIL: a census missing a record was ACCEPTED -- the table would silently shorten"; fail=1
else
    echo "   PASS: a census missing a record is rejected, not quietly dropped"
fi
rm -rf "$d"

echo
echo "== 6. a probe cannot be swapped for one that fails differently (negative control) =="
# The control for check 2, planted rather than assumed. Each case below is an
# attack that check 2 used to pass. The last case is the positive control: if
# probes.sh rejected everything it would score full marks here while being
# useless, which is the same defect one level up.
pd=$(mktemp -d)
p_expect() {   # <label> <expect-non-zero?> — run probes.sh on $pd and judge
    sh bin/probes.sh "$pd" >/dev/null 2>&1; rc=$?
    if [ "$2" = "reject" ] && [ "$rc" -eq 0 ]; then
        echo "   FAIL: $1 -- ACCEPTED"; fail=1
    elif [ "$2" = "accept" ] && [ "$rc" -ne 0 ]; then
        echo "   FAIL: $1 -- rejected a legitimate probe (exit $rc)"; fail=1
    else
        echo "   PASS: $1"
    fi
}
cat > "$pd/tiny_probe.lean" <<'PROBE_EOF'
namespace Tiny
axiom tiny_cheat : (0:Nat) = 1
theorem tiny_bad : (0:Nat) = 1 := tiny_cheat
end Tiny
PROBE_EOF

# (a) no declaration at all
p_expect "a probe with no .expect is refused" reject

# (b) declaration present but empty of assertions
printf '# only a comment\n' > "$pd/tiny_probe.expect"
p_expect "an .expect that is comments-only is refused" reject

# (c) THE ATTACK: the probe fails, but not for the reason it declares. This is
#     the plain-ASCII swap of unicode_probe.lean, in miniature.
printf 'Uni.\316\264gap_normal\n' > "$pd/tiny_probe.expect"
p_expect "a probe that fails for the WRONG reason is refused" reject

# (d) declaration with no body
printf 'Tiny.tiny_cheat\n' > "$pd/orphan_probe.expect"
printf 'Tiny.tiny_cheat\n' > "$pd/tiny_probe.expect"
p_expect "an .expect whose .lean is gone is refused" reject
rm -f "$pd/orphan_probe.expect"

# (e) positive control -- an honest probe must still pass, or (a)-(d) prove nothing
p_expect "an honest probe, declaring its real signature, is accepted" accept
rm -rf "$pd"

echo
echo "== 7. the ledger is well-formed, and nothing is ripe for escalation =="
if sh bin/ledger.sh ledger >/dev/null; then
    echo "   PASS"
else
    echo "   FAIL: see above. A class with >=2 open sites and no mechanism is red by design."
    fail=1
fi

echo
echo "== 8. the ledger gate cannot be satisfied vacuously (negative control) =="
# The control for check 7. A ledger validator that accepted anything would make
# the ledger FAILURES.md again -- prose that cannot be thresholded, which is the
# thing it exists to replace. Needs no toolchain.
ld=$(mktemp -d); TAB=$(printf '\t')
l_case() {  # <label> <accept|reject>
    sh bin/ledger.sh "$ld" >/dev/null 2>&1; rc=$?
    if [ "$2" = "reject" ] && [ "$rc" -eq 0 ]; then echo "   FAIL: $1 -- ACCEPTED"; fail=1
    elif [ "$2" = "accept" ] && [ "$rc" -ne 0 ]; then echo "   FAIL: $1 -- rejected a valid ledger (exit $rc)"; fail=1
    else echo "   PASS: $1"; fi
}
mkclasses() { printf "%s\n" "$1" > "$ld/classes.tsv"; }
mksites()   { printf "%s\n" "$1" > "$ld/sites.tsv"; }
mkgates()   { printf "%s\n" "$1" > "$ld/gates.tsv"; }
VALID_C="AAA${TAB}a machine${TAB}grep aaa"
VALID_S="AAA${TAB}some/file.sh${TAB}open"
VALID_G="g:1${TAB}AAA${TAB}a control"

mkclasses "$VALID_C"; mksites "$VALID_S"; mkgates "$VALID_G"
l_case "a valid ledger is accepted (positive control)" accept

mkclasses "# only comments"
l_case "an empty classes.tsv is refused" reject
mkclasses "$VALID_C"

mksites "BBB${TAB}some/file.sh${TAB}open"
l_case "a site naming an unknown class is refused" reject

mksites "$(printf 'AAA%ssame%sopen\nAAA%ssame%sclosed' "$TAB" "$TAB" "$TAB" "$TAB")"
l_case "a duplicated (class, site) row is refused" reject

mksites "AAA${TAB}some/file.sh${TAB}maybe"
l_case "a site state that is neither open nor closed is refused" reject
mksites "$VALID_S"

mkclasses "AAA${TAB}a machine${TAB}-"
l_case "a mechanism with no search key is refused" reject

mkclasses "AAA${TAB}a machine${TAB}grep aaa${TAB}extra"
l_case "a row with the wrong number of fields is refused" reject
mkclasses "$VALID_C"

mkgates "g:1${TAB}AAA${TAB}-"
l_case "a gate declaring no control is refused" reject

mkgates "g:1${TAB}ZZZ${TAB}a control"
l_case "a gate closing an unknown class is refused" reject
mkgates "$VALID_G"

# THE ESCALATION ITSELF. If this one does not fire, the threshold is decoration.
mkclasses "AAA${TAB}-${TAB}-"
mksites "$(printf 'AAA%ssite/one%sopen\nAAA%ssite/two%sopen' "$TAB" "$TAB" "$TAB" "$TAB")"
l_case "2 open sites with no mechanism turns the build red" reject

# ...and does NOT fire at one open site, or the threshold is just a ban.
mksites "$(printf 'AAA%ssite/one%sopen\nAAA%ssite/two%sclosed' "$TAB" "$TAB" "$TAB" "$TAB")"
l_case "1 open site with no mechanism stays local (threshold, not a ban)" accept
rm -rf "$ld"

echo
echo "== 9. the feedback channel is well-formed, and no gate is ripe for deletion =="
# The DOWNWARD arrow. Checks 7-8 push mechanisms UP from defects; this pushes
# deletions DOWN from lived experience. Without it escalation is a ratchet and
# |G| only rises -- which GOVERNANCE.md warns about and this branch already did,
# taking |G| from 4 to 8 in the session that wrote the warning.
if sh bin/feedback.sh ledger; then
    echo "   PASS"
else
    echo "   FAIL: a gate with >=2 friction reports and no field catch is a"
    echo "         deletion candidate by design. Delete it or record a catch."
    fail=1
fi

echo
echo "== 10. the deletion threshold fires, and only when it should (negative control) =="
# A threshold that never fires is decoration; one that always fires is a ban.
# Both are the same defect as a gate whose name overclaims, one level up.
fd=$(mktemp -d); cp ledger/*.tsv "$fd/"
quiet=$(grep -v '^#' ledger/events.tsv | grep -v '^[[:space:]]*$' | awk -F'\t' '$2=="control-only"{print $1; exit}')
if [ -z "$quiet" ]; then
    echo "   FAIL: no control-only gate to test the threshold against"; fail=1
else
    printf '%s\tprobe\tcost\n%s\tprobe\tblocked\n' "$quiet" "$quiet" >> "$fd/friction.tsv"
    sh bin/feedback.sh "$fd" >/dev/null 2>&1
    if [ $? -ne 0 ]; then echo "   PASS: 2 friction + 0 field-catches is refused ($quiet)"
    else echo "   FAIL: threshold did not fire at 2 friction reports"; fail=1; fi
    cp ledger/*.tsv "$fd/"
    printf '%s\tprobe\tcost\n' "$quiet" >> "$fd/friction.tsv"
    sh bin/feedback.sh "$fd" >/dev/null 2>&1
    if [ $? -eq 0 ]; then echo "   PASS: 1 friction report alone does not condemn a gate"
    else echo "   FAIL: threshold fired at 1 -- that is a ban, not a threshold"; fail=1; fi
fi
rm -rf "$fd"

echo
if [ "$fail" -eq 0 ]; then echo "ALL GATES PASS"; else echo "GATES FAILED"; fi
exit $fail
